def make_image(post_id: int, index: int, color, label: str) -> str:
    """매물 사진을 만들어 uploads 폴더에 저장하고 경로를 돌려줌.

    실제 물건 사진은 구할 수 없으니 색과 도형으로 대신함.
    사진마다 도형 배치를 바꿔서 "같은 물건을 다른 각도로 찍은" 느낌을 냄 —
    사진 도용 탐지가 다른 각도를 오해하지 않는지도 함께 시험할 수 있음
    """
    from PIL import Image, ImageDraw

    os.makedirs(UPLOAD_DIR, exist_ok=True)

    W = H = 600

    # 매물 번호로 색과 배치를 조금씩 흔듦.
    # 같은 물건이 두 번 나와도 사진이 달라야 함 —
    # 안 그러면 사진 도용 탐지가 "같은 사진" 으로 잡아버림
    rnd = random.Random(post_id * 100 + index)
    shift = lambda c, n: tuple(max(0, min(255, v + n)) for v in c)

    color = shift(color, rnd.randint(-25, 25))
    bg = shift(color, 90)
    dark = shift(color, -40)

    img = Image.new("RGB", (W, H), bg)
    d = ImageDraw.Draw(img)

    # 배치도 매물마다 조금씩 다르게
    dx, dy = rnd.randint(-40, 40), rnd.randint(-40, 40)

    if index == 0:
        d.rounded_rectangle((90 + dx, 170 + dy, 510 + dx, 430 + dy), radius=24, fill=color)
        d.ellipse((250 + dx, 90 + dy, 350 + dx, 190 + dy), fill=dark)
    elif index == 1:
        d.rounded_rectangle((150 + dx, 110 + dy, 450 + dx, 470 + dy), radius=24, fill=color)
        d.ellipse((100 + dx, 300 + dy, 220 + dx, 420 + dy), fill=dark)
    else:
        d.ellipse((120 + dx, 120 + dy, 480 + dx, 480 + dy), fill=color)
        d.rounded_rectangle((260 + dx, 60 + dy, 340 + dx, 180 + dy), radius=12, fill=dark)

    # 사진마다 지문이 확실히 갈리도록 무늬를 넉넉히 뿌림.
    # pHash 는 사진을 8x8 로 줄여서 비교하므로, 큰 덩어리가 흩어져 있어야
    # 서로 다른 사진으로 구분됨
    for _ in range(rnd.randint(10, 16)):
        x, y = rnd.randint(20, 520), rnd.randint(20, 520)
        w = rnd.randint(40, 110)
        h = rnd.randint(40, 110)
        tone = shift(color, rnd.choice([-70, -35, 35, 70]))
        if rnd.random() < 0.5:
            d.ellipse((x, y, x + w, y + h), fill=tone)
        else:
            d.rounded_rectangle((x, y, x + w, y + h), radius=10, fill=tone)

    # 한글 글꼴이 있으면 물건 이름을 얹음 (없으면 도형만)
    try:
        from PIL import ImageFont
        for path in (r"C:\Windows\Fonts\malgun.ttf",
                     "/usr/share/fonts/truetype/nanum/NanumGothic.ttf"):
            if os.path.exists(path):
                font = ImageFont.truetype(path, 32)
                box = d.textbbox((0, 0), label, font=font)
                d.text(((W - box[2]) / 2, 515), label, font=font, fill=(70, 70, 70))
                break
    except Exception:
        pass

    name = f"demo_{post_id}_{index}_{uuid.uuid4().hex[:8]}.png"
    img.save(os.path.join(UPLOAD_DIR, name))
    return f"/{UPLOAD_DIR}/{name}"


def make_users(db, count=10):
    """가짜 회원 만들기. 이미 있으면 그대로 씀"""
    pw = bcrypt.hashpw(b"pass1234", bcrypt.gensalt()).decode()
    users = []

    for i in range(count):
        username = f"demo{i:02d}"
        found = db.query(User).filter(User.username == username).first()
        if found:
            users.append(found)
            continue

        u = User(
            username=username,
            password_hash=pw,
            nickname=NICKNAMES[i % len(NICKNAMES)] + str(i),
            region=random.choice(REGIONS),
            name=f"테스트{i:02d}",
            email=f"demo{i:02d}@example.com",
            phone=f"010-9{i:03d}-{i:04d}",
            address="서울시 어딘가 " + str(100 + i),
        )
        db.add(u)
        users.append(u)

    db.commit()
    for u in users:
        db.refresh(u)
    return users


def make_posts(db, users, count=172):
    """가짜 매물 만들기. 매물마다 사진 1~3장도 함께 만듦"""
    rows = []
    for i in range(count):
        title, category, price, color = ITEMS[i % len(ITEMS)]
        seller = random.choice(users)
        # 지역을 돌아가며 배정 — 판매자 동네를 따르면 한쪽에 몰림.
        # 40개를 8개 지역에 나누면 지역마다 5개씩 들어감
        region = REGIONS[i % len(REGIONS)]
        # 며칠 전에 올린 것처럼
        when = datetime.utcnow() - timedelta(days=random.randint(0, 20),
                                             hours=random.randint(0, 23))
        p = Post(
            seller_id=seller.id,
            title=title if i < len(ITEMS) else f"{title} ({i})",
            content="직접 쓰던 물건입니다. 상태 좋아요. 편하게 문의주세요.",
            price=price,
            category=category,
            region=region,
            place_name=random.choice(["역 근처", "카페 앞", "아파트 정문", None]),
            created_at=when,
            bumped_at=when,
        )
        seller.total_posts += 1
        db.add(p)
        rows.append((p, color))

    db.commit()

    made = 0
    for p, color in rows:
        db.refresh(p)
        # 대부분 사진이 있고 일부는 없게 —
        # 사진 없는 매물이 화면에서 어떻게 보이는지도 확인하려고
        if random.random() < 0.85:
            for idx in range(random.randint(1, 3)):
                db.add(PostImage(
                    post_id=p.id,
                    image_url=make_image(p.id, idx, color, p.title),
                    sort_order=idx,
                ))
                made += 1

    db.commit()
    print(f"사진 {made}장 생성")
    return [p for p, _ in rows]



def make_chat(db, post, buyer, stage):
    """대화 한 건 만들기.
    stage = 어디까지 진행됐는지 — "talking" / "reserved" / "done" """
    room = ChatRoom(post_id=post.id, buyer_id=buyer.id)
    db.add(room)
    db.flush()

    seller = post.seller
    # 대화가 시작된 시각
    t = post.created_at + timedelta(hours=random.randint(1, 30))

    def say(who, text):
        nonlocal t
        t += timedelta(minutes=random.randint(1, 25))
        db.add(Message(room_id=room.id, sender_id=who.id, content=text, created_at=t))

    def system(text):
        nonlocal t
        t += timedelta(minutes=random.randint(1, 10))
        db.add(Message(room_id=room.id, sender_id=None, content=text,
                       kind="system", created_at=t))

    # 1) 첫 인사
    say(buyer, random.choice(BUYER_OPEN))
    say(seller, random.choice(SELLER_OPEN))

    # 2) 문의 1~3번
    for _ in range(random.randint(1, 3)):
        say(buyer, random.choice(BUYER_ASK))
        say(seller, random.choice(SELLER_ANSWER))

    if stage == "talking":
        room.last_message_at = t
        return room

    # 3) 약속 잡기
    say(buyer, random.choice(BUYER_TIME))
    say(seller, random.choice(SELLER_TIME))

    # 4) 구매 결정
    room.buyer_decided_at = t
    system(f"{buyer.nickname}님이 구매를 결정했어요")
    post.status = "예약중"

    if stage == "reserved":
        room.last_message_at = t
        return room

    # 5) 만나는 날 대화
    for _ in range(random.randint(1, 3)):
        say(random.choice([buyer, seller]), random.choice(MEETING))

    # 6) 판매 확인 → 거래 확정
    room.seller_confirmed_at = t
    system(f"{seller.nickname}님이 판매를 확인했어요")
    system("거래가 확정됐어요")
    post.status = "거래완료"
    seller.completed_deals += 1
    buyer.completed_purchases += 1

    # 7) 마무리 인사
    say(buyer, random.choice(CLOSING))
    say(seller, random.choice(CLOSING))

    room.last_message_at = t
    return room


def make_reviews(db, room, post, buyer):
    """거래가 끝난 방에 후기 남기기. 양쪽 다 쓰기도, 한쪽만 쓰기도 함"""
    seller = post.seller

    def write(reviewer, reviewee):
        rating = random.choices([5, 4, 3, 2], weights=[55, 30, 10, 5])[0]
        tags = random.sample(GOOD_TAGS, random.randint(0, 2)) if rating >= 4 else []
        db.add(Review(
            room_id=room.id,
            reviewer_id=reviewer.id,
            reviewee_id=reviewee.id,
            rating=rating,
            tags=",".join(tags),
            comment=random.choice(COMMENTS),
            created_at=room.last_message_at + timedelta(minutes=random.randint(5, 300)),
        ))
        # 매너온도 반영
        delta = {1: -0.5, 2: -0.3, 3: 0.0, 4: 0.15, 5: 0.3}[rating]
        reviewee.manner_temp = round(min(99.0, max(0.0, reviewee.manner_temp + delta)), 1)

    # 70%는 양쪽 다, 20%는 한쪽만, 10%는 아무도 안 씀
    roll = random.random()
    if roll < 0.7:
        write(buyer, seller)
        write(seller, buyer)
    elif roll < 0.9:
        write(random.choice([buyer, seller]),
              seller if random.random() < 0.5 else buyer)


