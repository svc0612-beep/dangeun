        users = make_users(db, count=10)
        posts = make_posts(db, users, count=172)
        print(f"회원 {len(users)}명, 매물 {len(posts)}개 준비")

        rooms = 0
        for post in posts:
            # 매물 하나에 1~3명이 문의
            others = [u for u in users if u.id != post.seller_id]
            for buyer in random.sample(others, random.randint(1, 3)):
                # 이미 방이 있으면 건너뜀
                dup = (
                    db.query(ChatRoom)
                    .filter(ChatRoom.post_id == post.id, ChatRoom.buyer_id == buyer.id)
                    .first()
                )
                if dup:
                    continue

                stage = random.choices(
                    # 거래완료된 매물은 목록에서 빠지므로 비율을 낮게 잡음.
                    # 매물 40개 중 대부분이 목록에 남아야 검색·필터를 시험할 수 있음
                    ["talking", "reserved", "done"], weights=[72, 18, 10]
                )[0]
                # 이미 팔린 매물이면 더는 확정 못 함
                if post.status == "거래완료":
                    stage = "talking"

                room = make_chat(db, post, buyer, stage)
                rooms += 1

                if stage == "done":
                    make_reviews(db, room, post, buyer)

        db.commit()

        msgs = db.query(Message).count()
        revs = db.query(Review).count()
        print(f"대화방 {rooms}개, 메시지 {msgs}줄, 후기 {revs}개 생성 완료")
