def build_synonym_map() -> dict[str, set[str]]:
    """검색어 → 함께 찾을 말들 로 바꿔둠.

    한 낱말이 여러 줄에 있을 수 있어서(예: "갤럭시"는 폰 줄과 갤럭시폰 줄에)
    그 줄들을 모두 합침
    """
    table: dict[str, set[str]] = {}
    for group in SYNONYM_GROUPS:
        # 공백을 없애면 "갤럭시 S24" 같은 제목과 안 맞으므로 그대로 둠
        words = {w.lower() for w in group}
        for word in words:
            table.setdefault(word, set()).update(words)
    return table


# 미리 만들어두고 계속 씀
SYNONYMS = build_synonym_map()


def expand_query(word: str) -> list[str]:
    """검색어를 같은 말들로 넓힘. 사전에 없으면 자기 자신만"""
    key = (word or "").lower().strip()
    if key in SYNONYMS:
        # 원래 검색어를 맨 앞에 두어 그 결과가 먼저 오게
        rest = sorted(SYNONYMS[key] - {key})
        return [word] + rest
    return [word]


