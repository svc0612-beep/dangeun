# ---------------------------------------------------------------
# 글자 씻어내기
# ---------------------------------------------------------------

def join_jamo(text: str) -> str:
    """흩어진 자모를 글자로 합침.

    "ㄱㅐㅅㅐㄲㅣ" → "개새끼"
    한글은 첫소리·가운뎃소리·끝소리로 이뤄지므로,
    자모가 그 순서로 나열돼 있으면 되돌릴 수 있음
    """
    out = []
    i = 0
    n = len(text)

    while i < n:
        ch = text[i]

        # 첫소리가 될 수 있는 자음이고, 다음이 모음이면 합쳐봄
        if ch in CHO and i + 1 < n and text[i + 1] in JUNG:
            cho_i = CHO.index(ch)
            jung_i = JUNG.index(text[i + 1])
            jong_i = 0
            step = 2

            # 그다음이 받침이 될 자음이고, 그 뒤가 모음이 아니면 받침으로 봄
            if i + 2 < n and text[i + 2] in JONG[1:]:
                nxt = text[i + 3] if i + 3 < n else ""
                if nxt not in JUNG:
                    jong_i = JONG.index(text[i + 2])
                    step = 3

            out.append(chr(0xAC00 + cho_i * 588 + jung_i * 28 + jong_i))
            i += step
        else:
            out.append(ch)
            i += 1

    return "".join(out)


def normalize(text: str) -> str:
    """비교하기 좋게 씻어냄.

    공백·기호·숫자를 없애고, 흩어진 자모를 합침
    """
    if not text:
        return ""

    # 한글·영문만 남김 (숫자·기호·공백 제거)
    cleaned = re.sub(r"[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z]", "", text)
    # 흩어진 자모를 글자로
    joined = join_jamo(cleaned)
    return joined.lower()


