# 검사
# ---------------------------------------------------------------

def find_bad(text: str) -> list[str]:
    """걸린 나쁜 말들을 돌려줌. 없으면 빈 목록"""
    if not text:
        return []

    clean = normalize(text)
    hits = []

    # 1) 씻어낸 글자에 나쁜 말이 들어있는지
    for word in BAD_WORDS:
        if word in clean:
            hits.append(word)

    # 2) 초성만 쓴 경우. 원문에 자음만 이어진 덩어리가 있는지 봄
    only_cho = re.sub(r"[^ㄱ-ㅎ]", "", text)
    for pattern in BAD_CHOSUNG:
        if pattern in only_cho:
            hits.append(pattern)

    # 3) 씻어낸 글의 초성이 나쁜 초성과 맞는지
    #    ("개 새 끼" 를 합친 뒤 초성을 뽑으면 ㄱㅅㄲ)
    cho_of_clean = to_chosung(clean)
    for pattern in BAD_CHOSUNG:
        if pattern in cho_of_clean and len(pattern) >= 3:
            # 두 글자짜리(ㅅㅂ)는 우연히 맞을 수 있어 세 글자 이상만
            hits.append(pattern)

    # 같은 것이 여러 번 걸릴 수 있으니 정리
    return sorted(set(hits))


def is_clean(text: str) -> bool:
    """추천 문구로 써도 되는 말인지"""
    return len(find_bad(text)) == 0


def classify(text: str) -> tuple[str, list[str]]:
    """무엇이 걸렸는지 종류까지 알려줌.

    돌려주는 값 — ("curse" 욕설 / "scam" 사기 / "other" 그 밖 / "" 깨끗함, 걸린 말들)
    안내 문구를 종류에 맞게 띄우려고 나눔
    """
    hits = find_bad(text)
    if not hits:
        return "", []

    curse_set = set(CURSES) | BAD_CHOSUNG
    if any(h in curse_set for h in hits):
        return "curse", hits
    if any(h in SCAMS for h in hits):
        return "scam", hits
    return "other", hits
